#!/usr/bin/env node
/**
 * Per-base copies of the story files (spec 56, 1.6.4), as
 * lib/example-variants.mjs makes the example variants. For each base, every
 * packages/shadcn-table/stories/<dir>/<Name>.stories.tsx is copied to
 * stories/.<base>/<dir>-<Name>.stories.tsx (gitignored) with its imports
 * pointed at the docs app:
 *   - `@/components/ui/...` to the base's library copy, `@/components/ui-<base>/...`
 *   - `storybook/test` to ./storybook-test, a stand-in whose exports do
 *     nothing: the docs never run a play, and no test library reaches a
 *     visitor's bundle
 *   - `@storybook/react-vite` (types only) to `@storybook/react`
 *   - `../../.storybook/themes` to ./themes, which names the base (`ST_BASE`)
 * Nothing else changes. Each folder also gets index.json, every story's file
 * key, export and source path, and sources.json, the story files as written,
 * for the code view (components/story-example.tsx reads both).
 *
 * Runs before `next build`, `next dev` and `types:check` (package.json
 * `build`, `predev`, `types:check`). Stale copies are removed.
 *
 * Usage (apps/shadcn-table-docs): node lib/story-variants.mjs
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BASES } from '../../../tools/registry/bases.mjs';
import { readStories, STORIES_DIR } from './story-pages.mjs';

const APP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(APP, 'stories');
const SUFFIX = '.stories.tsx';

/** The copy's file key: the path under stories/ with `/` as `-`, no suffix. */
export const fileKey = (file) =>
  file.slice(0, -SUFFIX.length).replaceAll('/', '-');

/**
 * One base's copy of one story file.
 * @param {string} source
 * @param {string} base
 */
export const rewriteStory = (source, base) =>
  source
    .replace(/(['"])@\/components\/ui\//g, `$1@/components/ui-${base}/`)
    .replace(/(['"])storybook\/test\1/g, `$1./storybook-test$1`)
    .replace(/(['"])@storybook\/react-vite\1/g, `$1@storybook/react$1`)
    .replace(/(['"])(?:\.\.\/)+\.storybook\/themes\1/g, `$1./themes$1`);

/**
 * Every copy is left out of the docs type check: the story files are not
 * type-checked where they live (packages/shadcn-table has no gate over
 * stories/), and four of them do not pass `tsc` there either.
 */
const COPY_HEADER =
  '// @ts-nocheck: generated by lib/story-variants.mjs. Do not edit.\n';

/** The stand-in for `storybook/test`: every export accepts any call and returns itself. */
const TEST_STUB = `// Generated by lib/story-variants.mjs. Do not edit.
// The docs never run a story's play: these stand in for storybook/test, with
// its types (a type import, erased from the bundle), so no test library
// reaches the docs bundle.
import type * as Test from 'storybook/test';

const stub = new Proxy<() => void>(() => {}, {
  get: (_target, key) => (key === 'then' ? undefined : stub),
  apply: () => stub,
}) as never;
export const expect: typeof Test.expect = stub;
export const within: typeof Test.within = stub;
export const waitFor: typeof Test.waitFor = stub;
export const userEvent: typeof Test.userEvent = stub;
export const fireEvent: typeof Test.fireEvent = stub;
export const spyOn: typeof Test.spyOn = stub;
export const screen: typeof Test.screen = stub;
export const fn: typeof Test.fn = stub;
`;

const themes = (base) => `// Generated by lib/story-variants.mjs. Do not edit.
/** The base this copy renders with (packages/shadcn-table/.storybook/themes.ts). */
export const ST_BASE: 'base' | 'radix' | 'aria' = ${JSON.stringify(base)};
`;

async function main() {
  const stories = await readStories();
  const files = [...new Set(stories.map((story) => story.file))];
  /** @type {Record<string, string>} */
  const sources = {};
  for (const file of files) {
    sources[fileKey(file)] = await fs.readFile(
      path.join(STORIES_DIR, file),
      'utf8',
    );
  }
  const index = Object.fromEntries(
    stories.map((story) => [
      story.id,
      {
        key: fileKey(story.file),
        exportName: story.exportName,
        name: story.name,
        title: story.title,
        file: story.file,
      },
    ]),
  );
  for (const base of BASES) {
    const out = path.join(OUT, `.${base}`);
    await fs.mkdir(out, { recursive: true });
    const written = new Set([
      'storybook-test.ts',
      'themes.ts',
      'index.json',
      'sources.json',
    ]);
    for (const [key, source] of Object.entries(sources)) {
      const name = `${key}${SUFFIX}`;
      written.add(name);
      await fs.writeFile(
        path.join(out, name),
        COPY_HEADER + rewriteStory(source, base),
      );
    }
    await fs.writeFile(path.join(out, 'storybook-test.ts'), TEST_STUB);
    await fs.writeFile(path.join(out, 'themes.ts'), themes(base));
    await fs.writeFile(
      path.join(out, 'index.json'),
      `${JSON.stringify(index)}\n`,
    );
    await fs.writeFile(
      path.join(out, 'sources.json'),
      `${JSON.stringify(sources)}\n`,
    );
    for (const entry of await fs.readdir(out)) {
      if (!written.has(entry)) {
        await fs.rm(path.join(out, entry), { recursive: true });
      }
    }
    console.log(
      `stories/.${base}: ${files.length} story files, ${stories.length} stories`,
    );
  }
}

await main();
