#!/usr/bin/env node
/**
 * Generates examples/map.tsx from the file system:
 *   - examples/<reference edition>/<slug>/   one component per example,
 *     `<PascalCase(slug)>Example`, rendering `<ExampleSnippet name={slug} />`
 *     (the reference set defines the example list; every edition folder
 *     carries the same slugs, pnpm check:bases guards it)
 *   - example-groups/<Name>.tsx              default export registered as <Name>
 *
 * The example components are exported individually (example-groups import
 * them) and together as `exampleComponents`, which components/mdx.tsx
 * spreads, so an MDX page can use <BasicExample /> or <FilteringExamples />
 * without a hand-written import. The output is formatted with the repo's
 * prettier config. Run after adding or removing an example; never edit
 * map.tsx by hand.
 *
 * Usage: node scripts/example-map.mjs
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { REFERENCE_EDITION } from '../../../packages/shadcn-table/scripts/registry/editions.mjs';
import { pascal } from '../lib/example-pages.mjs';

const APP_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const EXAMPLES = path.join(APP_DIR, 'examples', REFERENCE_EDITION);
const GROUPS = path.join(APP_DIR, 'example-groups');
const OUT = path.join(APP_DIR, 'examples', 'map.tsx');

async function exists(p) {
  return fs
    .access(p)
    .then(() => true)
    .catch(() => false);
}

async function main() {
  const slugs = [];
  for (const entry of (
    await fs.readdir(EXAMPLES, { withFileTypes: true })
  ).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    if (!(await exists(path.join(EXAMPLES, entry.name, 'TS.tsx')))) continue;
    slugs.push(entry.name);
  }
  const examples = slugs.map((slug) => ({
    name: `${pascal(slug)}Example`,
    slug,
  }));
  const groups = (await exists(GROUPS))
    ? (await fs.readdir(GROUPS))
        .filter((f) => f.endsWith('.tsx'))
        .map((f) => f.slice(0, -4))
        .sort()
    : [];
  const names = [...examples.map((e) => e.name), ...groups];
  const dupes = names.filter((n, i, a) => a.indexOf(n) !== i);
  if (dupes.length) throw new Error(`duplicate registry names: ${dupes}`);

  const lines = [
    '// Generated by scripts/example-map.mjs. Do not edit.',
    "import { ExampleSnippet } from '@/components/mdx/example-snippet';",
    ...groups.map((name) => `import ${name} from '@/example-groups/${name}';`),
    '',
    ...examples.map(
      (e) =>
        `export const ${e.name} = () => <ExampleSnippet name="${e.slug}" />;`,
    ),
    '',
    'export const exampleComponents = {',
    ...names.map((name) => `  ${name},`),
    '};',
    '',
  ];
  const config = await prettier.resolveConfig(OUT);
  await fs.writeFile(
    OUT,
    await prettier.format(lines.join('\n'), { ...config, filepath: OUT }),
  );
  console.log(
    `examples/map.tsx: ${names.length} components (${examples.length} examples)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
