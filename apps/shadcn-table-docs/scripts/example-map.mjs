#!/usr/bin/env node
/**
 * Generates two maps and the locale list from the file system:
 *   - examples/map.tsx: one component per example folder of the reference
 *     base, examples/<reference base>/<slug>/ (every base folder
 *     carries the same slugs, pnpm check:bases guards it), named
 *     `<PascalCase(slug)>Example` and rendering `<ExampleSnippet name={slug} />`,
 *     exported individually and together as `exampleComponents`. The example
 *     groups (example-groups/<Name>.tsx) import the components from here.
 *   - example-groups/map.tsx: `exampleComponents` of examples/map.tsx plus
 *     every group's default export registered as <Name>. components/mdx.tsx
 *     spreads it, so an MDX page can use <BasicExample /> or
 *     <FilteringExamples /> without a hand-written import. A separate file
 *     because the groups build their panels at module level from the
 *     example components: one file holding both would import itself.
 *   - lib/locales.ts: every locale the library ships, read from the committed
 *     packages/shadcn-table/registry.json through `baseItems` (the call
 *     scripts/install.mjs makes): the codes of the locale items plus `en`,
 *     which ships inside the library item, each with its
 *     `ST_Localization_*` export name, its English language name and its
 *     `localization-i18n-<code>` example slug. A new locale always adds that
 *     example, so the list is rerun with the maps.
 *
 * The output is formatted with the repo's prettier config. Run after adding
 * or removing an example, group or locale; never edit any output by hand.
 *
 * Usage: node scripts/example-map.mjs
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import {
  baseItems,
  PKG,
  REFERENCE_BASE,
} from '../../../packages/shadcn-table/scripts/registry/lib.mjs';
import { ENTRY_FILE } from '../lib/example-files.mjs';
import { pascal } from '../lib/example-pages.mjs';

const APP_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const EXAMPLES = path.join(APP_DIR, 'examples', REFERENCE_BASE);
const GROUPS = path.join(APP_DIR, 'example-groups');
const EXAMPLES_OUT = path.join(APP_DIR, 'examples', 'map.tsx');
const GROUPS_OUT = path.join(GROUPS, 'map.tsx');
const LOCALES_OUT = path.join(APP_DIR, 'lib', 'locales.ts');

const HEADER = '// Generated by scripts/example-map.mjs. Do not edit.';

/** Writes `lines` to `file`, formatted. */
async function writeFormatted(file, lines) {
  const config = await prettier.resolveConfig(file);
  await fs.writeFile(
    file,
    await prettier.format(lines.join('\n'), { ...config, filepath: file }),
  );
}

/** The locale file that ships inside the library item. */
const BUILT_IN_LOCALE = /(^|\/)locales\/en\.ts$/;

/** `ST_Localization_*`, the one locale export of a locale file. */
async function exportName(file) {
  const src = await fs.readFile(path.join(PKG, file), 'utf8');
  const match = src.match(/export const (ST_Localization_\w+)/);
  if (!match) throw new Error(`no ST_Localization_* export in ${file}`);
  return match[1];
}

/**
 * The locales of the reference base: one per locale item (`<item>-locale-<code>`)
 * plus `en` from the library item. The library item is `main` until spec 11
 * splits it and `core` after; whichever of the two lists the `en` file is
 * read, so both registry shapes work.
 */
async function readLocales(slugs) {
  const catalog = JSON.parse(
    await fs.readFile(path.join(PKG, 'registry.json'), 'utf8'),
  );
  const items = baseItems(catalog, REFERENCE_BASE);
  const holder = [items.main, items.core].find((item) =>
    item?.files.some((file) => BUILT_IN_LOCALE.test(file.path)),
  );
  if (!holder) throw new Error(`no ${REFERENCE_BASE} item ships en.ts`);
  const entries = [
    {
      code: 'en',
      file: holder.files.find((file) => BUILT_IN_LOCALE.test(file.path)).path,
    },
    ...items.locales.map((item) => ({
      code: item.name.slice(item.name.indexOf('-locale-') + '-locale-'.length),
      file: item.files[0].path,
    })),
  ].sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));
  const names = new Intl.DisplayNames(['en'], {
    type: 'language',
    fallback: 'code',
  });
  const out = [];
  for (const { code, file } of entries) {
    const slug = `localization-i18n-${code}`.toLowerCase();
    const example = slugs.find((s) => s.toLowerCase() === slug);
    if (!example) throw new Error(`no example ${slug} for locale ${code}`);
    let label = code;
    try {
      label = names.of(code) ?? code;
    } catch {
      // A code Intl rejects keeps itself as its label.
    }
    out.push({ code, exportName: await exportName(file), label, example });
  }
  return out;
}

async function main() {
  const slugs = [];
  for (const entry of (
    await fs.readdir(EXAMPLES, { withFileTypes: true })
  ).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    const entryFile = path.join(EXAMPLES, entry.name, ENTRY_FILE);
    const hasEntry = await fs
      .access(entryFile)
      .then(() => true)
      .catch(() => false);
    if (!hasEntry) continue;
    slugs.push(entry.name);
  }
  const examples = slugs.map((slug) => ({
    name: `${pascal(slug)}Example`,
    slug,
  }));
  const groups = (await fs.readdir(GROUPS))
    .filter((f) => f.endsWith('.tsx') && f !== 'map.tsx')
    .map((f) => f.slice(0, -4))
    .sort();
  const names = [...examples.map((e) => e.name), ...groups];
  const dupes = names.filter((n, i, a) => a.indexOf(n) !== i);
  if (dupes.length) throw new Error(`duplicate registry names: ${dupes}`);

  await writeFormatted(EXAMPLES_OUT, [
    HEADER,
    "import { ExampleSnippet } from '@/components/mdx/example-snippet';",
    '',
    ...examples.map(
      (e) =>
        `export const ${e.name} = () => <ExampleSnippet name="${e.slug}" />;`,
    ),
    '',
    'export const exampleComponents = {',
    ...examples.map((e) => `  ${e.name},`),
    '};',
    '',
  ]);
  await writeFormatted(GROUPS_OUT, [
    HEADER,
    "import { exampleComponents as examples } from '@/examples/map';",
    ...groups.map((name) => `import ${name} from './${name}';`),
    '',
    'export const exampleComponents = {',
    '  ...examples,',
    ...groups.map((name) => `  ${name},`),
    '};',
    '',
  ]);
  const locales = await readLocales(slugs);
  await writeFormatted(LOCALES_OUT, [
    HEADER,
    '',
    '/** A locale the library ships. */',
    'export interface DocsLocale {',
    '  /** File and item code: `de`, `pt-BR`, `sr-Cyrl-RS`. */',
    '  readonly code: string;',
    '  /** `ST_Localization_DE`, `ST_Localization_PT_BR`. */',
    '  readonly exportName: string;',
    '  /** English language name, `German`; the code when Intl has none. */',
    '  readonly label: string;',
    '  /** The docs example that renders it, `localization-i18n-<code>`. */',
    '  readonly example: string;',
    '}',
    '',
    `/** Every locale, \`en\` included, sorted by code (${locales.length}). */`,
    `export const locales: readonly DocsLocale[] = ${JSON.stringify(locales)};`,
    '',
    `/** The registry's locale items: every locale except \`en\`, which ships with the table (${locales.length - 1}). */`,
    'export const installableLocales: readonly DocsLocale[] = locales.filter(',
    "  (locale) => locale.code !== 'en',",
    ');',
    '',
  ]);
  console.log(
    `examples/map.tsx: ${examples.length} examples; example-groups/map.tsx: ${names.length} components; lib/locales.ts: ${locales.length} locales`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
