#!/usr/bin/env node
/**
 * Generates examples/map.ts from the file system:
 *   - examples/<name>/index.tsx   default export registered as <PascalCase(name)>Example
 *   - example-groups/<Name>.tsx   default export registered as <Name>
 *
 * components/mdx.tsx spreads the generated map, so an MDX page can use
 * <BasicExample /> or <FilteringExamples /> without a hand-written import.
 * Run after adding or removing an example; never edit map.ts by hand.
 *
 * Usage: node scripts/example-map.mjs
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const EXAMPLES = path.join(APP_DIR, 'examples');
const GROUPS = path.join(APP_DIR, 'example-groups');
const OUT = path.join(EXAMPLES, 'map.ts');

const pascal = (s) =>
  s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');

async function exists(p) {
  return fs
    .access(p)
    .then(() => true)
    .catch(() => false);
}

async function main() {
  const entries = [];
  const examples = (await fs.readdir(EXAMPLES, { withFileTypes: true }))
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
  for (const name of examples) {
    if (!(await exists(path.join(EXAMPLES, name, 'index.tsx')))) continue;
    entries.push({
      name: `${pascal(name)}Example`,
      from: `@/examples/${name}`,
    });
  }
  if (await exists(GROUPS)) {
    const groups = (await fs.readdir(GROUPS))
      .filter((f) => f.endsWith('.tsx'))
      .map((f) => f.slice(0, -4))
      .sort();
    for (const name of groups) {
      entries.push({ name, from: `@/example-groups/${name}` });
    }
  }
  const dupes = entries
    .map((e) => e.name)
    .filter((n, i, a) => a.indexOf(n) !== i);
  if (dupes.length) throw new Error(`duplicate registry names: ${dupes}`);

  const lines = [
    '// Generated by scripts/example-map.mjs. Do not edit.',
    ...entries.map((e) => `import ${e.name} from '${e.from}';`),
    '',
    'export const exampleComponents = {',
    ...entries.map((e) => `  ${e.name},`),
    '};',
    '',
  ];
  await fs.writeFile(OUT, lines.join('\n'));
  console.log(
    `examples/map.ts: ${entries.length} components (${examples.length} examples)`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
