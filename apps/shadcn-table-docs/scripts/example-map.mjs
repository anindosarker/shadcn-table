#!/usr/bin/env node
/**
 * Generates two maps from the file system:
 *   - examples/map.tsx: one component per example folder of the reference
 *     edition, examples/<reference edition>/<slug>/ (every edition folder
 *     carries the same slugs, pnpm check:bases guards it), named
 *     `<PascalCase(slug)>Example` and rendering `<ExampleSnippet name={slug} />`,
 *     exported individually and together as `exampleComponents`. The example
 *     groups (example-groups/<Name>.tsx) import the components from here.
 *   - example-groups/map.tsx: `exampleComponents` of examples/map.tsx plus
 *     every group's default export registered as <Name>. components/mdx.tsx
 *     spreads it, so an MDX page can use <BasicExample /> or
 *     <FilteringExamples /> without a hand-written import. A separate file
 *     because the groups build their panels at module level from the
 *     example components: one file holding both would import itself.
 *
 * The output is formatted with the repo's prettier config. Run after adding
 * or removing an example or group; never edit either map by hand.
 *
 * Usage: node scripts/example-map.mjs
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { REFERENCE_EDITION } from '../../../packages/shadcn-table/scripts/registry/editions.mjs';
import { pascal } from '../lib/example-pages.mjs';

const APP_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const EXAMPLES = path.join(APP_DIR, 'examples', REFERENCE_EDITION);
const GROUPS = path.join(APP_DIR, 'example-groups');
const EXAMPLES_OUT = path.join(APP_DIR, 'examples', 'map.tsx');
const GROUPS_OUT = path.join(GROUPS, 'map.tsx');

const HEADER = '// Generated by scripts/example-map.mjs. Do not edit.';

/** Writes `lines` to `file`, formatted. */
async function writeFormatted(file, lines) {
  const config = await prettier.resolveConfig(file);
  await fs.writeFile(
    file,
    await prettier.format(lines.join('\n'), { ...config, filepath: file }),
  );
}

async function main() {
  const slugs = [];
  for (const entry of (
    await fs.readdir(EXAMPLES, { withFileTypes: true })
  ).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory()) continue;
    const entryFile = path.join(EXAMPLES, entry.name, "TS.tsx");
    const hasEntry = await fs
      .access(entryFile)
      .then(() => true)
      .catch(() => false);
    if (!hasEntry) continue;
    slugs.push(entry.name);
  }
  const examples = slugs.map((slug) => ({
    name: `${pascal(slug)}Example`,
    slug,
  }));
  const groups = (await fs.readdir(GROUPS))
    .filter((f) => f.endsWith('.tsx') && f !== 'map.tsx')
    .map((f) => f.slice(0, -4))
    .sort();
  const names = [...examples.map((e) => e.name), ...groups];
  const dupes = names.filter((n, i, a) => a.indexOf(n) !== i);
  if (dupes.length) throw new Error(`duplicate registry names: ${dupes}`);

  await writeFormatted(EXAMPLES_OUT, [
    HEADER,
    "import { ExampleSnippet } from '@/components/mdx/example-snippet';",
    '',
    ...examples.map(
      (e) =>
        `export const ${e.name} = () => <ExampleSnippet name="${e.slug}" />;`,
    ),
    '',
    'export const exampleComponents = {',
    ...examples.map((e) => `  ${e.name},`),
    '};',
    '',
  ]);
  await writeFormatted(GROUPS_OUT, [
    HEADER,
    "import { exampleComponents as examples } from '@/examples/map';",
    ...groups.map((name) => `import ${name} from './${name}';`),
    '',
    'export const exampleComponents = {',
    '  ...examples,',
    ...groups.map((name) => `  ${name},`),
    '};',
    '',
  ]);
  console.log(
    `examples/map.tsx: ${examples.length} examples; example-groups/map.tsx: ${names.length} components`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
